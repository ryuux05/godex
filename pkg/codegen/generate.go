// Package codegen generates typed event bindings for Godex's supported ABIs.
package codegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"go/token"
	"math/big"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/ryuux05/godex/pkg/core/decoder"
)

const Header = "// Code generated by godex. DO NOT EDIT.\n"

type Config struct {
	Package string
	Type    string
	// Events selects names or canonical signatures. Empty selects all events.
	Events []string
}

type eventBinding struct {
	definition decoder.ABIItem
	name       string
	fields     []fieldBinding
}

type fieldBinding struct {
	input    decoder.ABIInput
	name     string
	goType   string
	accessor string
	bits     int
	signed   bool
}

// Generate returns formatted, deterministic Go source. It performs no I/O.
// Only events supported by the current Godex decoder may be selected.
func Generate(data []byte, cfg Config) ([]byte, error) {
	if !token.IsIdentifier(cfg.Package) || cfg.Package == "_" {
		return nil, fmt.Errorf("package must be a Go package identifier")
	}
	if !token.IsIdentifier(cfg.Type) || !unicode.IsUpper([]rune(cfg.Type)[0]) {
		return nil, fmt.Errorf("type must be an exported Go identifier, such as ERC20")
	}
	abi, err := readABI(data)
	if err != nil {
		return nil, err
	}
	selected, err := selectEvents(abi, cfg.Events)
	if err != nil {
		return nil, err
	}
	bindings := make([]eventBinding, 0, len(selected))
	usedNames := map[string]bool{cfg.Type + "ABI": true, cfg.Type + "Contract": true, cfg.Type + "Handlers": true}
	needsBigInt := false
	for i := range selected {
		event := &selected[i]
		name := exportedName(event.Name)
		if name == "" {
			return nil, fmt.Errorf("event %q has no usable Go name", event.Name)
		}
		for _, identifier := range []string{cfg.Type + name, "Parse" + cfg.Type + name} {
			if usedNames[identifier] {
				return nil, fmt.Errorf("event %q conflicts with generated name %s", event.Name, identifier)
			}
			usedNames[identifier] = true
		}
		binding := eventBinding{definition: *event, name: name}
		fieldNames, abiNames := map[string]bool{}, map[string]bool{}
		for j := range event.Inputs {
			input := &event.Inputs[j]
			if input.Name == "" || input.Name == "_" {
				input.Name = fmt.Sprintf("arg%d", j)
			}
			field, err := bindField(*input)
			if err != nil {
				return nil, fmt.Errorf("event %s field %s: %w", event.Name, input.Name, err)
			}
			if field.name == "" || fieldNames[field.name] || abiNames[input.Name] {
				return nil, fmt.Errorf("event %s has conflicting or invalid field name %q", event.Name, input.Name)
			}
			fieldNames[field.name], abiNames[input.Name] = true, true
			needsBigInt = needsBigInt || field.goType == "*big.Int"
			binding.fields = append(binding.fields, field)
		}
		binding.definition = *event
		bindings = append(bindings, binding)
	}
	embeddedABI, err := json.Marshal(selected)
	if err != nil {
		return nil, err
	}
	if err := decoder.NewStandardDecoder().RegisterABI("generated", string(embeddedABI)); err != nil {
		return nil, fmt.Errorf("unsupported event ABI: %w", err)
	}
	var out bytes.Buffer
	out.WriteString(Header)
	fmt.Fprintf(&out, "\npackage %s\n\nimport (\n\"context\"\n\"fmt\"\n", cfg.Package)
	if needsBigInt {
		out.WriteString("\"math/big\"\n")
	}
	out.WriteString("\n\"github.com/jackc/pgx/v5\"\n\"github.com/ryuux05/godex/pkg/godex\"\n)\n")
	fmt.Fprintf(&out, "\n// %sABI contains the selected events with normalized parameter names.\nconst %sABI = %q\n", cfg.Type, cfg.Type, embeddedABI)
	fmt.Fprintf(&out, "\n// %sContract selects exactly the events supported by these bindings.\nfunc %sContract(address string) godex.Contract {\nreturn godex.Contract{Address:address, ABI:%sABI}\n}\n", cfg.Type, cfg.Type, cfg.Type)
	for _, binding := range bindings {
		emitEvent(&out, cfg.Type, binding)
	}
	emitHandlers(&out, cfg.Type, bindings)
	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return source, nil
}

func readABI(data []byte) (decoder.ABI, error) {
	data = bytes.TrimSpace(data)
	if len(data) > 0 && data[0] == '{' {
		var artifact struct {
			ABI json.RawMessage `json:"abi"`
		}
		if err := json.Unmarshal(data, &artifact); err != nil {
			return nil, fmt.Errorf("parse ABI artifact: %w", err)
		}
		data = bytes.TrimSpace(artifact.ABI)
	}
	if len(data) == 0 || data[0] != '[' {
		return nil, fmt.Errorf("ABI must be a JSON array or an artifact containing an abi array")
	}
	var abi decoder.ABI
	if err := json.Unmarshal(data, &abi); err != nil {
		return nil, fmt.Errorf("parse ABI: %w", err)
	}
	for i := range abi {
		for j := range abi[i].Inputs {
			switch abi[i].Inputs[j].Type {
			case "uint":
				abi[i].Inputs[j].Type = "uint256"
			case "int":
				abi[i].Inputs[j].Type = "int256"
			}
		}
	}
	return abi, nil
}

func signature(event decoder.ABIItem) string {
	types := make([]string, 0, len(event.Inputs))
	for _, input := range event.Inputs {
		types = append(types, input.Type)
	}
	return event.Name + "(" + strings.Join(types, ",") + ")"
}

func selectEvents(abi decoder.ABI, selectors []string) (decoder.ABI, error) {
	var events decoder.ABI
	for _, event := range abi {
		if event.Type == "event" {
			events = append(events, event)
		}
	}
	selected := events
	if len(selectors) > 0 {
		selected = nil
		for _, selector := range selectors {
			var matches decoder.ABI
			for _, event := range events {
				if event.Name == selector || signature(event) == selector {
					matches = append(matches, event)
				}
			}
			if len(matches) != 1 {
				return nil, fmt.Errorf("event selector %q must match exactly one event; use a canonical signature for overloads", selector)
			}
			selected = append(selected, matches[0])
		}
	}
	if len(selected) == 0 {
		return nil, fmt.Errorf("ABI contains no selected events")
	}
	sort.Slice(selected, func(i, j int) bool { return signature(selected[i]) < signature(selected[j]) })
	names := map[string]bool{}
	for _, event := range selected {
		if names[event.Name] {
			return nil, fmt.Errorf("event name %q is duplicated or overloaded; generate one overload using -event and its canonical signature", event.Name)
		}
		names[event.Name] = true
		if event.Anonymous {
			return nil, fmt.Errorf("anonymous event %q is unsupported", event.Name)
		}
		indexed := 0
		for _, input := range event.Inputs {
			if input.Indexed {
				indexed++
			}
		}
		if indexed > 3 {
			return nil, fmt.Errorf("event %q has more than three indexed inputs", event.Name)
		}
	}
	return selected, nil
}

func exportedName(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	for i, part := range parts {
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		parts[i] = string(runes)
	}
	result := strings.Join(parts, "")
	if result != "" && unicode.IsDigit([]rune(result)[0]) {
		result = "Arg" + result
	}
	if strings.HasSuffix(result, "Id") {
		result = strings.TrimSuffix(result, "Id") + "ID"
	}
	return result
}

func bindField(input decoder.ABIInput) (fieldBinding, error) {
	f := fieldBinding{input: input, name: exportedName(input.Name)}
	switch input.Type {
	case "address":
		f.goType, f.accessor = "godex.Address", "Address"
	case "bool":
		f.goType, f.accessor = "bool", "Bool"
	case "bytes32":
		f.goType, f.accessor = "[32]byte", "Bytes32"
	case "string":
		f.goType, f.accessor = "string", "String"
	case "bytes":
		f.goType, f.accessor = "[]byte", "Bytes"
	default:
		f.signed = strings.HasPrefix(input.Type, "int")
		prefix := "uint"
		if f.signed {
			prefix = "int"
		}
		if !strings.HasPrefix(input.Type, prefix) {
			return f, fmt.Errorf("unsupported ABI type %q", input.Type)
		}
		width := strings.TrimPrefix(input.Type, prefix)
		bits, err := strconv.Atoi(width)
		if err != nil || bits < 8 || bits > 256 || bits%8 != 0 || width != strconv.Itoa(bits) {
			return f, fmt.Errorf("unsupported ABI type %q", input.Type)
		}
		f.bits = bits
		f.goType, f.accessor = "*big.Int", "BigInt"
		if bits == 8 || bits == 16 || bits == 32 || bits == 64 {
			f.goType, f.accessor = input.Type, "Uint64"
			if f.signed {
				f.accessor = "Int64"
			}
		}
	}
	if input.Indexed && (input.Type == "string" || input.Type == "bytes") {
		f.goType, f.accessor = "[32]byte", "Bytes32"
	}
	return f, nil
}

func emitEvent(out *bytes.Buffer, prefix string, binding eventBinding) {
	typeName := prefix + binding.name
	fmt.Fprintf(out, "\n// %s contains the decoded arguments of %s.\ntype %s struct {\n", typeName, binding.name, typeName)
	for _, field := range binding.fields {
		fmt.Fprintf(out, "%s %s\n", field.name, field.goType)
	}
	out.WriteString("}\n")
	fmt.Fprintf(out, "\n// Parse%s validates arguments and copies mutable values.\nfunc Parse%s(raw godex.Event) (%s,error) {\nvar result %s\n", typeName, typeName, typeName, typeName)
	fmt.Fprintf(out, "if raw.EventType != %q {return result,fmt.Errorf(\"expected event %%s, got %%q\",%q,raw.EventType)}\n", binding.definition.Name, binding.definition.Name)
	for i, field := range binding.fields {
		v := fmt.Sprintf("v%d", i)
		label := strings.ReplaceAll(typeName+"."+field.input.Name, "%", "%%")
		fmt.Fprintf(out, "%s,err:=raw.Fields.%s(%q)\nif err!=nil {return result,fmt.Errorf(%q,err)}\n", v, field.accessor, field.input.Name, label+": %w")
		if field.bits > 0 {
			condition := ""
			if field.goType == "*big.Int" {
				if field.signed {
					limit := new(big.Int).Lsh(big.NewInt(1), uint(field.bits-1))
					minimum := new(big.Int).Neg(limit)
					maximum := new(big.Int).Sub(limit, big.NewInt(1))
					fmt.Fprintf(out, "min%d,_:=new(big.Int).SetString(%q,10)\nmax%d,_:=new(big.Int).SetString(%q,10)\n", i, minimum.String(), i, maximum.String())
					condition = fmt.Sprintf("%s.Cmp(min%d)<0 || %s.Cmp(max%d)>0", v, i, v, i)
				} else {
					condition = fmt.Sprintf("%s.Sign()<0 || %s.BitLen()>%d", v, v, field.bits)
				}
			} else if field.bits < 64 {
				if field.signed {
					condition = fmt.Sprintf("%s < %d || %s > %d", v, -(int64(1) << (field.bits - 1)), v, (int64(1)<<(field.bits-1))-1)
				} else {
					condition = fmt.Sprintf("%s > %d", v, (uint64(1)<<field.bits)-1)
				}
			}
			if condition != "" {
				fmt.Fprintf(out, "if %s {return result,fmt.Errorf(%q)}\n", condition, label+": integer outside "+field.input.Type+" range")
			}
		}
		value := v
		if field.accessor == "Uint64" || field.accessor == "Int64" {
			value = field.goType + "(" + v + ")"
		}
		fmt.Fprintf(out, "result.%s=%s\n", field.name, value)
	}
	out.WriteString("return result,nil\n}\n")
}

func emitHandlers(out *bytes.Buffer, prefix string, bindings []eventBinding) {
	fmt.Fprintf(out, "\n// %sHandlers dispatches selected events inside the caller's PostgreSQL transaction.\n// Every callback is required. Pair Handle with a rollback function for projection writes.\ntype %sHandlers struct {\n", prefix, prefix)
	for _, event := range bindings {
		fmt.Fprintf(out, "On%s func(context.Context, pgx.Tx, godex.Event, %s%s) error\n", event.name, prefix, event.name)
	}
	out.WriteString("}\n")
	fmt.Fprintf(out, "\nfunc(h %sHandlers) Validate() error {\n", prefix)
	for _, event := range bindings {
		fmt.Fprintf(out, "if h.On%s==nil {return fmt.Errorf(%q)}\n", event.name, prefix+"Handlers.On"+event.name+" is required")
	}
	out.WriteString("return nil\n}\n")
	fmt.Fprintf(out, "\nfunc(h %sHandlers) Handle(ctx context.Context, tx pgx.Tx, raw godex.Event) error {\nif err:=h.Validate();err!=nil{return err}\nswitch raw.EventType {\n", prefix)
	for _, event := range bindings {
		fmt.Fprintf(out, "case %q:\nevent,err:=Parse%s%s(raw)\nif err!=nil{return err}\nreturn h.On%s(ctx,tx,raw,event)\n", event.definition.Name, prefix, event.name, event.name)
	}
	fmt.Fprintf(out, "default:return fmt.Errorf(%q,raw.EventType)\n}\n}\n", prefix+"Handlers: unsupported event %q")
}
